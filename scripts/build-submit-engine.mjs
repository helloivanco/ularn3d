import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { concatEngineFiles } from "../supabase/functions/_shared/engine-files.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = concatEngineFiles((rel) => readFileSync(join(root, "public/engine", rel), "utf8"));
const out = join(root, "supabase/functions/_shared/engine-source.js");
writeFileSync(
  out,
  `// Generated by scripts/build-submit-engine.mjs from public/engine. Do not edit.\nexport const ENGINE_SOURCE = ${JSON.stringify(source)};\n`,
);
console.log(`wrote ${out} (${source.length} chars)`);
