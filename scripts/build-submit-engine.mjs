import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { concatEngineFiles } from "../supabase/functions/_shared/engine-files.js";

const PART_COUNT = 8;
const PART_CHARS = 40000;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = concatEngineFiles((rel) => readFileSync(join(root, "public/engine", rel), "utf8"));
const shared = join(root, "supabase/functions/_shared");
const header = "// Generated by scripts/build-submit-engine.mjs from public/engine. Do not edit.\n";
const out = join(shared, "engine-source.js");
writeFileSync(out, `${header}export const ENGINE_SOURCE = ${JSON.stringify(source)};\n`);

const packed = gzipSync(Buffer.from(source)).toString("base64");
if (packed.length > PART_COUNT * PART_CHARS) {
  throw new Error(`engine bundle needs more than ${PART_COUNT} parts`);
}
for (let i = 0; i < PART_COUNT; i++) {
  const part = packed.slice(i * PART_CHARS, (i + 1) * PART_CHARS);
  writeFileSync(join(shared, `engine-part-${i}.js`), `${header}export const PART = ${JSON.stringify(part)};\n`);
}
const sha256 = createHash("sha256").update(source).digest("hex");
writeFileSync(
  join(shared, "engine-bundle-meta.js"),
  `${header}export const BUNDLED_ENGINE_SHA256 = ${JSON.stringify(sha256)};\nexport const ENGINE_PART_COUNT = ${PART_COUNT};\n`,
);
console.log(`wrote ${out} (${source.length} chars) and ${PART_COUNT} gzip parts`);
